-- 5.1 Signup: cria perfil + lista "Quero assistir"
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  base   text;
  final  text;
  n      int := 0;
begin
  base := lower(coalesce(new.raw_user_meta_data ->> 'apelido', ''));
  base := regexp_replace(base, '[^a-z0-9_]', '', 'g');
  base := left(base, 20);

  if char_length(base) < 3 then
    base := 'user_' || left(replace(new.id::text, '-', ''), 8);
  end if;

  final := base;
  while exists (select 1 from public.perfil where apelido = final) loop
    n := n + 1;
    final := left(base, 20 - char_length(n::text) - 1) || '_' || n;
  end loop;

  insert into public.perfil (id, apelido) values (new.id, final);

  insert into public.lista (perfil_id, titulo, tipo, visibilidade)
  values (new.id, 'Quero assistir', 'watchlist', 'privada');

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- 5.2 Protege a watchlist: não muda tipo, título nem visibilidade
create or replace function public.protege_watchlist()
returns trigger
language plpgsql
as $$
begin
  if old.tipo = 'watchlist' and (
       new.tipo <> old.tipo
    or new.titulo <> old.titulo
    or new.visibilidade <> old.visibilidade) then
    raise exception 'A lista "Quero assistir" não pode ser renomeada nem tornada pública'
      using errcode = 'check_violation';
  end if;
  if old.tipo = 'custom' and new.tipo = 'watchlist' then
    raise exception 'Não é possível converter uma lista em "Quero assistir"'
      using errcode = 'check_violation';
  end if;
  return new;
end;
$$;

drop trigger if exists lista_protege_watchlist on public.lista;
create trigger lista_protege_watchlist
  before update on public.lista
  for each row execute function public.protege_watchlist();

-- 5.3 Avaliação: registra data da última edição
create or replace function public.marca_avaliacao_editada()
returns trigger
language plpgsql
as $$
begin
  new.publicado_em := old.publicado_em;  -- data de publicação é imutável
  new.atualizado_em := now();
  return new;
end;
$$;

drop trigger if exists avaliacao_editada on public.avaliacao;
create trigger avaliacao_editada
  before update on public.avaliacao
  for each row execute function public.marca_avaliacao_editada();

