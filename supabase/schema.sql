create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------
-- 1. PERFIL  (1:1 com auth.users)
-- ---------------------------------------------------------------------
create table public.perfil (
  id         uuid primary key references auth.users (id) on delete cascade,
  apelido    text not null unique
             check (apelido ~ '^[a-z0-9_]{3,20}$'),
  criado_em  timestamptz not null default now()
);
comment on table public.perfil is 'Perfil público do usuário. Nunca guarda e-mail.';

-- ---------------------------------------------------------------------
-- 2. CATÁLOGO LOCAL (referências do TMDB)
-- ---------------------------------------------------------------------
create table public.serie (
  id               bigint generated by default as identity primary key,
  tmdb_id          integer not null unique,
  nome             text not null,
  sinopse          text,
  sinopse_idioma   text check (sinopse_idioma in ('pt-BR', 'en-US')),
  poster_path      text,
  backdrop_path    text,
  ano_estreia      integer check (ano_estreia between 1900 and 2100),
  generos          text[] not null default '{}',
  total_temporadas integer,
  atualizado_em    timestamptz not null default now()
);

create table public.temporada (
  id              bigint generated by default as identity primary key,
  serie_id        bigint not null references public.serie (id) on delete cascade,
  numero          integer not null check (numero >= 0),
  nome            text,
  poster_path     text,
  total_episodios integer,
  atualizado_em   timestamptz not null default now(),
  unique (serie_id, numero)
);

create table public.episodio (
  id              bigint generated by default as identity primary key,
  temporada_id    bigint not null references public.temporada (id) on delete cascade,
  numero          integer not null check (numero >= 0),
  nome            text,
  sinopse         text,
  sinopse_idioma  text check (sinopse_idioma in ('pt-BR', 'en-US')),
  data_exibicao   date,
  still_path      text,
  duracao_min     integer,
  unique (temporada_id, numero)
);

-- ---------------------------------------------------------------------
-- 3. DADOS DO USUÁRIO
-- ---------------------------------------------------------------------
create table public.diario (
  id           uuid primary key default gen_random_uuid(),
  perfil_id    uuid not null references public.perfil (id) on delete cascade,
  episodio_id  bigint not null references public.episodio (id) on delete cascade,
  assistido_em date not null,
  revisita     boolean not null default false,
  criado_em    timestamptz not null default now()
);

create table public.avaliacao (
  id             uuid primary key default gen_random_uuid(),
  perfil_id      uuid not null references public.perfil (id) on delete cascade,
  serie_id       bigint not null references public.serie (id) on delete cascade,
  nota           numeric(2,1) not null
                 check (nota >= 0.5 and nota <= 5.0 and mod(nota * 10, 5) = 0),
  texto          text check (texto is null or char_length(texto) <= 10000),
  contem_spoiler boolean not null default false,
  publicado_em   timestamptz not null default now(),
  atualizado_em  timestamptz,
  unique (perfil_id, serie_id)
);

create table public.lista (
  id            uuid primary key default gen_random_uuid(),
  perfil_id     uuid not null references public.perfil (id) on delete cascade,
  titulo        text not null check (char_length(titulo) between 1 and 100),
  descricao     text check (descricao is null or char_length(descricao) <= 1000),
  tipo          text not null default 'custom'
                check (tipo in ('watchlist', 'custom')),
  visibilidade  text not null default 'publica'
                check (visibilidade in ('publica', 'privada')),
  criado_em     timestamptz not null default now(),
  -- "Quero assistir" é sempre privada
  constraint watchlist_privada check (tipo <> 'watchlist' or visibilidade = 'privada')
);
-- Apenas uma watchlist por perfil
create unique index lista_uma_watchlist_por_perfil
  on public.lista (perfil_id) where tipo = 'watchlist';

create table public.item_lista (
  lista_id      uuid not null references public.lista (id) on delete cascade,
  serie_id      bigint not null references public.serie (id) on delete cascade,
  ordem         integer not null default 0,
  adicionado_em timestamptz not null default now(),
  primary key (lista_id, serie_id)
);

create table public.seguidor (
  seguidor_id uuid not null references public.perfil (id) on delete cascade,
  seguido_id  uuid not null references public.perfil (id) on delete cascade,
  criado_em   timestamptz not null default now(),
  primary key (seguidor_id, seguido_id),
  check (seguidor_id <> seguido_id)
);

create table public.curtida (
  perfil_id    uuid not null references public.perfil (id) on delete cascade,
  avaliacao_id uuid not null references public.avaliacao (id) on delete cascade,
  criado_em    timestamptz not null default now(),
  primary key (perfil_id, avaliacao_id)
);

