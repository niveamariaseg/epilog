-- PERFIL: leitura pública (só id/apelido/criado_em existem), edição do dono
create policy perfil_select on public.perfil
  for select using (true);
create policy perfil_update on public.perfil
  for update using (id = (select auth.uid())) with check (id = (select auth.uid()));

-- CATÁLOGO: leitura pública; escrita apenas via service_role (backend)
create policy serie_select     on public.serie     for select using (true);
create policy temporada_select on public.temporada for select using (true);
create policy episodio_select  on public.episodio  for select using (true);

-- DIÁRIO: estritamente privado
create policy diario_select on public.diario
  for select using (perfil_id = (select auth.uid()));
create policy diario_insert on public.diario
  for insert with check (perfil_id = (select auth.uid()));
create policy diario_update on public.diario
  for update using (perfil_id = (select auth.uid())) with check (perfil_id = (select auth.uid()));
create policy diario_delete on public.diario
  for delete using (perfil_id = (select auth.uid()));

-- AVALIAÇÃO: leitura pública; escrita do autor
create policy avaliacao_select on public.avaliacao
  for select using (true);
create policy avaliacao_insert on public.avaliacao
  for insert with check (perfil_id = (select auth.uid()));
create policy avaliacao_update on public.avaliacao
  for update using (perfil_id = (select auth.uid())) with check (perfil_id = (select auth.uid()));
create policy avaliacao_delete on public.avaliacao
  for delete using (perfil_id = (select auth.uid()));

-- LISTA: pública ou do dono; o usuário só cria listas custom e só apaga custom
create policy lista_select on public.lista
  for select using (visibilidade = 'publica' or perfil_id = (select auth.uid()));
create policy lista_insert on public.lista
  for insert with check (perfil_id = (select auth.uid()) and tipo = 'custom');
create policy lista_update on public.lista
  for update using (perfil_id = (select auth.uid())) with check (perfil_id = (select auth.uid()));
create policy lista_delete on public.lista
  for delete using (perfil_id = (select auth.uid()) and tipo = 'custom');

-- ITEM_LISTA: segue a visibilidade da lista; escrita só pelo dono da lista
create policy item_lista_select on public.item_lista
  for select using (exists (
    select 1 from public.lista l
    where l.id = item_lista.lista_id
      and (l.visibilidade = 'publica' or l.perfil_id = (select auth.uid()))));
create policy item_lista_insert on public.item_lista
  for insert with check (exists (
    select 1 from public.lista l
    where l.id = item_lista.lista_id and l.perfil_id = (select auth.uid())));
create policy item_lista_update on public.item_lista
  for update using (exists (
    select 1 from public.lista l
    where l.id = item_lista.lista_id and l.perfil_id = (select auth.uid())));
create policy item_lista_delete on public.item_lista
  for delete using (exists (
    select 1 from public.lista l
    where l.id = item_lista.lista_id and l.perfil_id = (select auth.uid())));

-- SEGUIDOR: relações públicas; cada um gerencia quem segue
create policy seguidor_select on public.seguidor
  for select using (true);
create policy seguidor_insert on public.seguidor
  for insert with check (seguidor_id = (select auth.uid()));
create policy seguidor_delete on public.seguidor
  for delete using (seguidor_id = (select auth.uid()));

-- CURTIDA: contagem pública; cada um gerencia as próprias
create policy curtida_select on public.curtida
  for select using (true);
create policy curtida_insert on public.curtida
  for insert with check (perfil_id = (select auth.uid()));
create policy curtida_delete on public.curtida
  for delete using (perfil_id = (select auth.uid()));

